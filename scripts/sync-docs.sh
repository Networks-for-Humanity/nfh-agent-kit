#!/usr/bin/env bash
# Refresh the offline docs indexes in llms/ from each docs site's llms.txt.
# Usage: scripts/sync-docs.sh
set -euo pipefail
cd "$(dirname "$0")/.."
fetch() {  # name url
  local out="llms/docs-index-$1.md"
  { echo "<!-- Generated by scripts/sync-docs.sh from $2 on $(date -u +%F). Do not edit by hand. -->"
    curl -fsSL "$2" | sed '/^# Agent Instructions/,$d'
  } > "$out.tmp" && mv "$out.tmp" "$out"
  echo "$out: $(grep -c '^- \[' "$out") pages"
}
fetch nfh       https://docs.nfh.global/llms.txt
fetch finternet https://docs.finternetlab.io/llms.txt
fetch dedi      https://dedi-global.gitbook.io/docs/llms.txt
{ printf '# Finternet / UNITS docs pages\n\nEvery page is Markdown. Fetch the URL directly. Regenerate with `scripts/sync-docs.sh`; this list is copied from `llms/docs-index-finternet.md`.\n\n'
  grep '^- \[' llms/docs-index-finternet.md; } > skills/nfh-units/references/finternet-pages.md
